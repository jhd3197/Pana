"""Turn a generated take into the game's mp3 with seamless loop points.

  uv run --project <ACE-Step-1.5> python scripts/music/loop.py [--only id,id] [--take N]

The intro plays once, then [loopStart, loopEnd] repeats. Both points sit on
beats chosen so the music around them sounds alike, and the bar before
loopEnd is crossfaded into the bar before loopStart, so the jump is inaudible.
Writes the mp3 at the song's `out` and refreshes engine/music-tracks.js.
"""

import argparse
import json
import subprocess
import tempfile
from pathlib import Path

import librosa
import numpy as np
import pyloudnorm
import soundfile as sf

HERE = Path(__file__).resolve().parent
PANA = HERE.parents[1]
ACE = HERE.parents[3] / "ACE-Step-1.5"
RATE = 44100
TARGET_LUFS = -20.0  # -16 drowned the synthesized effects
PICKS = HERE / "picks.json"


def beat_features(mono, beats):
    chroma = librosa.feature.chroma_cqt(y=mono, sr=RATE)
    mfcc = librosa.feature.mfcc(y=mono, sr=RATE, n_mfcc=13)
    rms = librosa.feature.rms(y=mono)
    feats = np.vstack([chroma, mfcc / 40, rms * 20])
    sync = librosa.util.sync(feats, librosa.time_to_frames(beats, sr=RATE), aggregate=np.mean)
    return sync / (np.linalg.norm(sync, axis=0, keepdims=True) + 1e-9)


def find_loop(audio, song):
    mono = audio.mean(axis=1)
    length = len(mono) / RATE
    _, frames = librosa.beat.beat_track(y=mono, sr=RATE, start_bpm=song["bpm"], tightness=400)
    beats = librosa.frames_to_time(frames, sr=RATE)
    feats = beat_features(mono, beats)
    # Skip the generated fade-out: the loop must end while the band still plays.
    env = librosa.feature.rms(y=mono)[0]
    loud = np.median(env)
    tail = librosa.frames_to_time(np.nonzero(env > loud * 0.6)[0][-1], sr=RATE)
    bar = 6 if song["time"] == "6" else int(song["time"])
    win = 2 * bar
    best = (-1, None, None)
    for i, s in enumerate(beats):
        if s < 1.5 or s > length * 0.35 or i < win:
            continue
        for j in range(i + 4 * bar, len(beats)):
            e = beats[j]
            if e < length * 0.6 or e > tail - 2 or j + win >= feats.shape[1]:
                continue
            if (j - i) % bar:
                continue
            # What leads into each point and what follows it should match.
            score = float(np.mean(np.sum(feats[:, i - win:i + win] * feats[:, j - win:j + win], axis=0)))
            score += 0.002 * (e - s)  # prefer longer loops when close
            if score > best[0]:
                best = (score, i, j)
    if best[1] is None:
        raise RuntimeError("no loop found")
    i, j = best[1], best[2]
    return beats[i], beats[j], best[0], 60 / np.median(np.diff(beats))


def build(audio, start, end, fade):
    s, e, f = (int(round(x * RATE)) for x in (start, end, fade))
    t = np.linspace(0, np.pi / 2, f)[:, None]
    blend = audio[e - f:e] * np.cos(t) + audio[s - f:s] * np.sin(t)
    pad = audio[s:s + RATE]  # what follows loopEnd, so decoder padding never cuts in
    return np.concatenate([audio[:e - f], blend, pad])


def finish_once(audio):
    mono = np.abs(audio).mean(axis=1)
    keep = np.nonzero(mono > 1e-3)[0]
    audio = audio[keep[0]:keep[-1] + 1]
    fade = min(len(audio), int(0.4 * RATE))
    audio[-fade:] *= np.linspace(1, 0, fade)[:, None]
    return audio


def encode(audio, out):
    meter = pyloudnorm.Meter(RATE)
    audio = pyloudnorm.normalize.loudness(audio, meter.integrated_loudness(audio), TARGET_LUFS)
    audio = np.clip(audio, -0.98, 0.98)
    out.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory() as tmp:
        wav = Path(tmp) / "x.wav"
        sf.write(wav, audio, RATE)
        subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", str(wav), "-codec:a", "libmp3lame", "-b:a", "128k", str(out)], check=True)


def url_for(out):
    parts = Path(out).parts
    if parts[0] == "engine":
        return "/" + "/".join(parts)
    return f"/g/{parts[1]}/" + "/".join(parts[3:])


def write_manifest(spec, loops):
    lines = [
        "// Generated by scripts/music/loop.py: every recorded song and its loop points.",
        "// The intro plays once, then [loop[0], loop[1]] seconds repeat. Songs without",
        "// a loop play once (stingers). See docs/knowledge/music.md.",
        "export const SONGS = {",
    ]
    for song in spec["songs"]:
        info = loops.get(song["id"])
        if not info:
            continue
        loop = f", loop: [{info['loop'][0]:.4f}, {info['loop'][1]:.4f}]" if info.get("loop") else ""
        lines.append(f"  '{song['id']}': {{ src: '{url_for(song['out'])}', bpm: {round(info['bpm'])}{loop} }},")
    lines.append("};")
    (PANA / "engine" / "music-tracks.js").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--only", default="")
    ap.add_argument("--take", type=int, default=0, help="take to use; 0 = picks.json or 1")
    args = ap.parse_args()
    spec = json.loads((HERE / "songs.json").read_text(encoding="utf-8"))
    picks = json.loads(PICKS.read_text(encoding="utf-8")) if PICKS.exists() else {}
    loops_file = HERE / "loops.json"
    loops = json.loads(loops_file.read_text(encoding="utf-8")) if loops_file.exists() else {}
    only = {s for s in args.only.split(",") if s}
    for song in spec["songs"]:
        if only and song["id"] not in only:
            continue
        take = args.take or picks.get(song["id"], 1)
        src = ACE / "output" / "pana" / song["id"] / f"take-{take}.wav"
        if not src.exists():
            print(f"missing {src}")
            continue
        audio, sr = librosa.load(src, sr=RATE, mono=False)
        audio = np.ascontiguousarray(audio.T if audio.ndim == 2 else np.stack([audio, audio], 1))
        if song.get("loop", True):
            start, end, score, bpm = find_loop(audio, song)
            built = build(audio, start, end, 60 / bpm)
            loops[song["id"]] = {"take": take, "loop": [start, end], "bpm": bpm, "score": score}
            print(f"{song['id']}: take {take}, loop {start:.2f}-{end:.2f}s ({end - start:.1f}s), {bpm:.0f} bpm, match {score:.3f}")
        else:
            built = finish_once(audio)
            loops[song["id"]] = {"take": take, "bpm": song["bpm"]}
            print(f"{song['id']}: take {take}, one-shot {len(built) / RATE:.1f}s")
        encode(built, PANA / song["out"])
    loops_file.write_text(json.dumps(loops, indent=2), encoding="utf-8")
    write_manifest(spec, loops)


if __name__ == "__main__":
    main()
