// node cache.browser.js [absolute-playwright-package] [browser-executable]
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdir } from 'node:fs/promises';
const { chromium } = createRequire(import.meta.url)(process.argv[2] || 'playwright');
const browser = await chromium.launch({ headless: true, ...(process.argv[3] ? { executablePath: process.argv[3] } : {}) });
const base = process.env.PANA_QA_URL || 'http://localhost:8461', output = 'art/studio/inspector';
await mkdir(output, { recursive: true });
const errors = [];
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(`${base}/studio.html`);
  await page.waitForFunction(() => window.panaLibrary?.thumbnails.state.ready >= 3, null, { timeout: 90000 });
  await page.locator('#cache-pause').click();
  await page.waitForFunction(() => !panaLibrary.thumbnails.state.active);
  const paused = await page.evaluate(() => panaLibrary.thumbnails.state);
  const box = await page.locator('[data-asset="pana"]').boundingBox(); assert.ok(box.height > 100 && box.width > 100);
  await page.waitForTimeout(800);
  assert.equal(await page.evaluate(() => panaLibrary.thumbnails.state.generated), paused.generated);
  await page.locator('[data-category="Objetos"]').click();
  await page.locator('[data-asset="corn"]').click();
  await page.waitForFunction(() => panaLibrary.selected === 'corn' && document.querySelector('#preview-status').hidden);
  await page.locator('#camera-view').selectOption('top');
  assert.ok(await page.evaluate(() => panaLibrary.camera.position.y > 1));
  await page.locator('#grid').click(); await page.locator('#wireframe').click();
  assert.equal(await page.locator('#grid').getAttribute('aria-pressed'), 'false');
  assert.equal(await page.evaluate(() => { let all = true; panaLibrary.current.group.traverse(o => { for (const m of Array.isArray(o.material) ? o.material : o.material ? [o.material] : []) all &&= m.wireframe; }); return all; }), true);
  await page.locator('#wireframe').click(); await page.locator('#grid').click(); await page.locator('#camera-view').selectOption('perspective');
  await page.locator('#view-list').click(); await page.locator('#sort').selectOption('name');
  assert.ok(await page.locator('#asset-list').getAttribute('class').then(value => value.includes('list')));
  await page.locator('#view-grid').click(); await page.locator('#sort').selectOption('catalog');
  await page.locator('[data-category="Todos"]').click(); await page.locator('#cache-pause').click();
  await page.waitForFunction(() => {
    const cache = panaLibrary.thumbnails;
    return cache.state.ready + cache.errors.size === panaLibrary.assets.length && !cache.state.active;
  }, null, { timeout: 300000 });
  const cold = await page.evaluate(() => ({ ...panaLibrary.thumbnails.state, errors: [...panaLibrary.thumbnails.errors] }));
  assert.equal(cold.ready, 60); assert.equal(cold.generated, 60); assert.equal(cold.validationError, ''); assert.deepEqual(cold.errors, []);
  assert.ok(cold.bytes > 20000 && cold.bytes < 10 * 1048576); console.log('Cold cache', cold);
  await page.locator('[data-asset="pana"]').click();
  await page.waitForFunction(() => panaLibrary.selected === 'pana' && document.querySelector('#preview-status').hidden);
  await page.screenshot({ path: `${output}/inventory.png` });
  const before = await page.evaluate(() => Object.fromEntries([...panaLibrary.thumbnails.entries].map(([id, entry]) => [id, entry.createdAt])));
  await page.reload();
  await page.waitForFunction(() => window.panaLibrary?.current && !panaLibrary.thumbnails.state.validating);
  const warm = await page.evaluate(() => panaLibrary.thumbnails.state);
  assert.equal(warm.reused, 60); assert.equal(warm.generated, 0); console.log('Warm cache: 60 reused, zero thumbnail builds');
  assert.ok(await page.locator('[data-asset="pana"] img').evaluate(img => img.complete && img.naturalWidth === 320));
  await page.locator('#sort').selectOption('triangles');
  const sorted = await page.locator('[data-asset]').evaluateAll(nodes => nodes.map(n => panaLibrary.thumbnails.entries.get(n.dataset.asset).stats.triangles));
  assert.deepEqual(sorted, [...sorted].sort((a, b) => b - a));
  await page.locator('#sort').selectOption('catalog');
  const frame = await page.evaluate(() => panaLibrary.renderer.info.render.frame);
  await page.waitForTimeout(500);
  assert.equal(await page.evaluate(() => panaLibrary.renderer.info.render.frame), frame);
  await page.locator('#animate').click();
  await page.waitForFunction(previous => panaLibrary.renderer.info.render.frame > previous + 2, frame);
  await page.locator('#animate').click();
  const downloadPromise = page.waitForEvent('download'); await page.locator('#export').click(); await (await downloadPromise).saveAs(`${output}/inventory.json`);
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.screenshot({ path: `${output}/mobile.png`, fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1000 });
  // Change a dependency response without touching the repository; consumers must invalidate.
  await page.route('**/engine/kitchen-props.js', async route => {
    const response = await route.fetch(); await route.fulfill({ response, body: (await response.text()) + '\n// cache invalidation test\n' });
  });
  await page.reload();
  await page.waitForFunction(() => window.panaLibrary && !panaLibrary.thumbnails.state.validating);
  const invalidated = await page.evaluate(() => panaLibrary.thumbnails.state);
  assert.ok(invalidated.reused > 0 && invalidated.reused < 60);
  await page.waitForFunction(() => panaLibrary.thumbnails.state.ready === 60 && !panaLibrary.thumbnails.state.active, null, { timeout: 180000 });
  const after = await page.evaluate(() => Object.fromEntries([...panaLibrary.thumbnails.entries].map(([id, entry]) => [id, entry.createdAt])));
  assert.ok(after.corn > before.corn); assert.ok(after.cocina > before.cocina); assert.equal(after.mango, before.mango);
  console.log('Dependency invalidation: kitchen props and kitchen map rebuilt; mango reused');
  await page.locator('#cache-rebuild').click();
  await page.waitForFunction(() => !panaLibrary.thumbnails.state.validating && panaLibrary.thumbnails.state.ready < 60);
  await page.locator('#cache-pause').click();
  await page.waitForFunction(() => !panaLibrary.thumbnails.state.active);
  assert.equal(await page.evaluate(() => panaLibrary.thumbnails.state.paused), true);
  const fallback = await browser.newPage();
  fallback.on('pageerror', error => errors.push(error.message));
  await fallback.addInitScript(() => { Object.defineProperty(window, 'indexedDB', { value: { open() { throw new Error('Storage disabled for test'); } } }); });
  await fallback.goto(`${base}/studio.html#corn`);
  await fallback.waitForFunction(() => window.panaLibrary?.thumbnails.state.ready >= 1, null, { timeout: 60000 });
  assert.equal(await fallback.evaluate(() => panaLibrary.thumbnails.state.persistent), false);
  assert.match(await fallback.locator('#cache-status').innerText(), /solo esta sesión/);
  assert.deepEqual(errors, []);
  console.log('PASS: cold/warm local cache, dependency invalidation, pause/resume/regeneration, storage fallback, inspector controls and mobile');
} finally { await browser.close(); }
