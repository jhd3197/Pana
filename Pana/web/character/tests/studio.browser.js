// Run against npm start. Optional arguments: Playwright package and browser binary.
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdir } from 'node:fs/promises';
import path from 'node:path';
const require = createRequire(import.meta.url);
const { chromium } = require(process.argv[2] || 'playwright');
const browser = await chromium.launch({ headless: true, ...(process.argv[3] ? { executablePath: process.argv[3] } : {}) });
const base = process.env.PANA_QA_URL || 'http://localhost:8461';
const output = process.env.PANA_QA_OUTPUT || 'art/character/qa';
await mkdir(output, { recursive: true });
const errors = [];
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 1 });
  page.on('pageerror', e => errors.push(e.message));
  page.on('console', msg => { if (msg.type() === 'error') errors.push(msg.text()); });
  await page.goto(`${base}/personaje.html`);
  await page.waitForFunction(() => window.panaStudio?.renderer.info.render.triangles > 0);
  await page.locator('#pause').click();
  for (const view of ['three-quarter', 'front', 'side', 'back']) {
    await page.locator(`[data-view="${view}"]`).click();
    await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
    await page.screenshot({ path: path.join(output, `${view}.png`), animations: 'disabled' });
  }
  const initial = await page.evaluate(() => ({ head: panaStudio.pana.head.uuid, body: panaStudio.pana.body.uuid, geo: panaStudio.renderer.info.memory.geometries }));
  await page.locator('[data-outfit="chef"]').click();
  assert.equal(await page.evaluate(() => panaStudio.pana.wardrobe.shirt.visible), false);
  assert.equal(await page.locator('[data-color]').first().isDisabled(), false);
  await page.locator('[data-view="front"]').click();
  await page.screenshot({ path: path.join(output, 'chef.png') });
  await page.locator('[data-outfit="shirt"]').click();
  await page.locator('[data-color="#3479cb"]').click();
  assert.equal(await page.evaluate(() => panaStudio.pana.wardrobe.color), '#3479cb');
  const identity = await page.evaluate(() => ({ head: panaStudio.pana.head.uuid, body: panaStudio.pana.body.uuid }));
  assert.equal(identity.head, initial.head); assert.equal(identity.body, initial.body);
  await page.locator('[data-pose="wave"]').click();
  await page.waitForFunction(() => panaStudio.pana.armR.rotation.z < -2);
  await page.screenshot({ path: path.join(output, 'wave.png') });
  await page.locator('[data-pose="walk"]').click();
  await page.waitForFunction(() => Math.abs(panaStudio.pana.legs[0].rotation.x) > 0.25);
  await page.locator('#pause').click();
  const pose = await page.evaluate(() => panaStudio.pana.legs[0].rotation.x);
  await page.waitForTimeout(180);
  assert.equal(await page.evaluate(() => panaStudio.pana.legs[0].rotation.x), pose);
  await page.locator('#rotate').click();
  const start = await page.evaluate(() => panaStudio.camera.position.x);
  await page.waitForFunction(x => Math.abs(panaStudio.camera.position.x - x) > 0.1, start);
  await page.locator('#reset').click();
  assert.equal(await page.evaluate(() => panaStudio.pana.wardrobe.color), '#ee3024');
  assert.equal(await page.evaluate(() => panaStudio.controls.autoRotate), false);
  await page.locator('[data-reference="three-quarter"]').click();
  await page.locator('#expand-reference').click(); assert.equal(await page.locator('dialog').isVisible(), true);
  await page.keyboard.press('Escape'); assert.equal(await page.locator('dialog').isVisible(), false);
  const downloadPromise = page.waitForEvent('download'); await page.locator('#capture').click();
  const download = await downloadPromise; assert.equal(download.suggestedFilename(), 'pana-personaje.png');
  await download.saveAs(path.join(output, 'capture.png'));
  const warmed = await page.evaluate(() => panaStudio.renderer.info.memory.geometries);
  for (let i = 0; i < 20; i++) await page.evaluate(i => { panaStudio.pana.setOutfit(i % 2 ? 'shirt' : 'chef'); panaStudio.pana.setColor(i % 2 ? '#f33e32' : '#3479cb'); }, i);
  assert.ok(await page.evaluate(() => panaStudio.renderer.info.memory.geometries) <= warmed);
  console.log('PASS: views, wardrobe identity, color, wave, walk, pause, orbit, reset, references, PNG and stable geometry count');
  console.log('Render:', await page.evaluate(() => ({ triangles: panaStudio.renderer.info.render.triangles, calls: panaStudio.renderer.info.render.calls, geometries: panaStudio.renderer.info.memory.geometries })));
  const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1, isMobile: true, hasTouch: true, reducedMotion: 'reduce' });
  mobile.on('pageerror', e => errors.push(e.message));
  await mobile.goto(`${base}/personaje.html`); await mobile.waitForFunction(() => !!window.panaStudio);
  assert.equal(await mobile.evaluate(() => panaStudio.paused), true);
  assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await mobile.screenshot({ path: path.join(output, 'mobile.png'), fullPage: true });
  assert.deepEqual(errors, []); console.log('PASS: 390px mobile, reduced motion and no browser errors');
} finally { await browser.close(); }
