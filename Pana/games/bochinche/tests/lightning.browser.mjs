import assert from 'node:assert/strict';
import path from 'node:path';
import os from 'node:os';
import { launch, base, waitFor } from '../../../tests/browser-kit.js';
const browser=await launch(),gamePath='/g/bochinche/';
try {
  const page=await browser.newPage({viewport:{width:1280,height:800},hasTouch:true}),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.addInitScript(()=>localStorage.setItem('pana:settings',JSON.stringify({quality:'baja',sound:false,music:false})));
  await page.goto(`${base}${gamePath}lightning.html?debug`);
  await waitFor(page,()=>window.PANA_PREPARED===true);
  assert(await page.evaluate(()=>lightningDebug.world.camera.isPerspectiveCamera));
  await page.locator('#slow').check();
  await page.locator('#cast').click();
  await waitFor(page,()=>lightningDebug.trial.phase==='charge'&&lightningDebug.effects.segments>0);
  await waitFor(page,()=>lightningDebug.trial.frozen&&lightningDebug.effects.flashing);
  await page.screenshot({path:path.join(os.tmpdir(),'pana-bochinche-lightning.png')});
  await waitFor(page,()=>lightningDebug.trial.phase==='done');
  assert.equal(await page.locator('#damage').innerText(),'12%');
  await page.locator('#baseline').click();
  await waitFor(page,()=>lightningDebug.trial.phase==='impact');
  assert.deepEqual(await page.evaluate(()=>({frozen:lightningDebug.trial.frozen,segments:lightningDebug.effects.segments,flash:lightningDebug.effects.flashing})),{frozen:false,segments:0,flash:false});
  await page.locator('#reset').click();
  assert.equal(await page.locator('#damage').innerText(),'0%');
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.locator('#cast').click();
  await waitFor(page,()=>lightningDebug.trial.phase==='impact');
  assert(await page.locator('#motion-note').isVisible());
  await page.locator('#reset').click();
  await page.setViewportSize({width:390,height:844});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.locator('#cast').scrollIntoViewIfNeeded();
  await page.locator('#cast').tap();
  await waitFor(page,()=>lightningDebug.trial.casts>=4);
  await page.locator('#reset').click();
  await page.screenshot({path:path.join(os.tmpdir(),'pana-bochinche-lightning-mobile.png'),fullPage:true});
  assert.deepEqual(errors,[]);
  console.log('Lightning lab: cast, hit-stop, baseline, reset, reduced motion and narrow layout passed.');
} finally {await browser.close();}
